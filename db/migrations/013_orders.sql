-- A single statement is atomic in autocommit and can also run inside initialization.
DO $migration$
DECLARE
  legacy_columns CONSTANT text[] := ARRAY[
    'comment:text', 'created_at:timestamp with time zone', 'delivery_date:date',
    'email:text', 'id:integer', 'name:text', 'phone:text', 'product_id:integer',
    'quantity:integer', 'status:text', 'user_id:integer'
  ];
  previous_lock_timeout text := current_setting('lock_timeout');
  has_order_requests boolean;
  actual_columns text[];
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  PERFORM pg_advisory_xact_lock(130013);

  IF to_regclass('public.products') IS NULL OR to_regclass('public.users') IS NULL
     OR to_regclass('public.orders') IS NULL THEN
    RAISE EXCEPTION '013: expected public.products, public.users and public.orders';
  END IF;

  has_order_requests := to_regclass('public.order_requests') IS NOT NULL;
  IF NOT has_order_requests THEN
    LOCK TABLE public.orders IN ACCESS EXCLUSIVE MODE;
    LOCK TABLE public.products IN ACCESS EXCLUSIVE MODE;
  END IF;

  SELECT array_agg(attname || ':' || format_type(atttypid, atttypmod) ORDER BY attname COLLATE "C")
  INTO actual_columns
  FROM pg_catalog.pg_attribute
  WHERE attrelid = CASE WHEN has_order_requests THEN 'public.order_requests' ELSE 'public.orders' END::regclass
    AND attnum > 0 AND NOT attisdropped;

  IF actual_columns IS DISTINCT FROM legacy_columns THEN
    RAISE EXCEPTION '013: legacy order requests have an unexpected layout';
  END IF;

  IF has_order_requests THEN
    -- The namespace is shared with the legacy tables. Verify the migration's
    -- constraints before treating existing relations as an already applied migration.
    IF to_regclass('public.order_items') IS NULL OR (
      SELECT count(*) FROM pg_catalog.pg_constraint
      WHERE convalidated AND (
        (conrelid = 'public.products'::regclass AND conname IN (
          'products_stock_nonnegative', 'products_farmer_id_fkey')) OR
        (conrelid = 'public.orders'::regclass AND conname IN (
          'orders_013_pkey', 'orders_013_user_id_fkey', 'orders_013_status_check', 'orders_013_total_price_check')) OR
        (conrelid = to_regclass('public.order_items') AND conname IN (
          'order_items_pkey', 'order_items_order_id_fkey', 'order_items_product_id_fkey',
          'order_items_quantity_check', 'order_items_unit_price_check'))
      )
    ) <> 11 OR (
      SELECT count(*) FROM pg_catalog.pg_index
      WHERE indisvalid AND (
        (indrelid = 'public.products'::regclass AND indexrelid = to_regclass('public.products_farmer_id_idx')) OR
        (indrelid = 'public.orders'::regclass AND indexrelid = to_regclass('public.orders_user_created_idx')) OR
        (indrelid = to_regclass('public.order_items') AND indexrelid = to_regclass('public.order_items_product_id_idx'))
      )
    ) <> 3 OR NOT EXISTS (
      SELECT 1 FROM pg_catalog.pg_attribute AS column_info
      JOIN pg_catalog.pg_attrdef AS default_info
        ON default_info.adrelid = column_info.attrelid AND default_info.adnum = column_info.attnum
      WHERE column_info.attrelid = 'public.products'::regclass AND column_info.attname = 'stock'
        AND column_info.atttypid = 'integer'::regtype AND column_info.attnotnull
        AND pg_get_expr(default_info.adbin, default_info.adrelid) = '0'
    ) THEN
      RAISE EXCEPTION '013: order_requests exists with an incomplete or conflicting orders schema';
    END IF;
    PERFORM set_config('lock_timeout', previous_lock_timeout, true);
    RETURN;
  END IF;

  IF to_regclass('public.order_items') IS NOT NULL OR EXISTS (
    SELECT 1 FROM pg_catalog.pg_attribute
    WHERE attrelid = 'public.products'::regclass AND attnum > 0 AND NOT attisdropped
      AND attname IN ('stock', 'farmer_id')
  ) THEN
    RAISE EXCEPTION '013: order_items or product inventory columns already exist without order_requests';
  END IF;

  ALTER TABLE public.orders RENAME TO order_requests;

  ALTER TABLE public.products
    ADD COLUMN stock INTEGER NOT NULL DEFAULT 0 CONSTRAINT products_stock_nonnegative CHECK (stock >= 0),
    ADD COLUMN farmer_id INTEGER CONSTRAINT products_farmer_id_fkey REFERENCES public.users(id) ON DELETE SET NULL;
  CREATE INDEX products_farmer_id_idx ON public.products (farmer_id);

  CREATE TABLE public.orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME public.orders_013_id_seq),
    user_id INTEGER NOT NULL CONSTRAINT orders_013_user_id_fkey REFERENCES public.users(id),
    status TEXT NOT NULL DEFAULT 'pending' CONSTRAINT orders_013_status_check
      CHECK (status IN ('pending', 'confirmed', 'completed', 'cancelled')),
    total_price BIGINT NOT NULL CONSTRAINT orders_013_total_price_check CHECK (total_price >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT orders_013_pkey PRIMARY KEY (id)
  );
  CREATE INDEX orders_user_created_idx ON public.orders (user_id, created_at DESC);

  CREATE TABLE public.order_items (
    order_id INTEGER NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES public.products(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price INTEGER NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (order_id, product_id)
  );
  CREATE INDEX order_items_product_id_idx ON public.order_items (product_id);

  PERFORM set_config('lock_timeout', previous_lock_timeout, true);
END;
$migration$;
